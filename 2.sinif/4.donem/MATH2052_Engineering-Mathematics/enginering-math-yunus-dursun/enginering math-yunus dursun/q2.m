f = @(z) 1i*z.^3 + z - 1i;
theta = linspace(0, 2*pi, 100);
z_circle = exp(1i*theta);
w_circle = f(z_circle);
figure;
plot(real(w_circle), imag(w_circle), 'b');
axis equal;
title('Image of |z| = 1 under w = iz^3 + z - i');
xlabel('Re(w)');
ylabel('Im(w)');
grid on;
z1 = 1;
z2 = 1 + 1i;
w1 = f(z1);
w2 = f(z2);
figure;
plot([real(w1), real(w2)], [imag(w1), imag(w2)], 'r', 'LineWidth', 2);
hold on;
scatter(real(w1), imag(w1), 'ro', 'MarkerSize', 10);
scatter(real(w2), imag(w2), 'ro', 'MarkerSize', 10);
axis equal;
title('Image of the line segment from 1 to 1+i under w = iz^3 + z - i');
xlabel('Re(w)');
ylabel('Im(w)');
grid on;
